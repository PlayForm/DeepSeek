#!/usr/bin/env node
//===============================================================================
// Generate-Specimens.mjs - the method specimen sheet CLI.
//===============================================================================
//
// Writes the inspection artefact the next milestone requires, BEFORE any mass
// regeneration of the 102 icons:
//
//   Reference/Specimens/Views.svg          nine construction specimens, each as
//                                          centerline / envelope / footprint
//   Reference/Specimens/Compositions.svg   four deliberately different scenes
//   Reference/Specimens/index.md           the specimen catalogue + clearance
//                                          numbers (a negative margin is an
//                                          overlap)
//
// Usage: node Maintain/Generate-Specimens.mjs
//===============================================================================
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compositionSvg, specimenSvg } from "./Icon/Specimens.mjs";

const Root = join(dirname(fileURLToPath(import.meta.url)), "..");
const Out = join(Root, "Reference", "Specimens");
mkdirSync(Out, { recursive: true });

const Views = specimenSvg();
const Compositions = compositionSvg();

writeFileSync(join(Out, "Views.svg"), Views.svg);
writeFileSync(join(Out, "Compositions.svg"), Compositions.svg);

const Table = (Rows, Key) =>
	[
		`| ${Key} | a | b | actual | required | margin | verdict |`,
		"| --- | --- | --- | ---: | ---: | ---: | --- |",
		...Rows.map(
			(Row) =>
				`| ${Row[Key]} | ${Row.a} | ${Row.b} | ${Row.actual} | ${Row.required} | ${Row.margin} | ${Row.ok ? "clear" : "OVERLAP"} |`,
		),
	].join("\n");

const Index = `# Specimens - the construction proof sheet

Generated by \`node Maintain/Generate-Specimens.mjs\`. This is the milestone that
must pass BEFORE the 102 icons are regenerated: it proves topology, terminals,
joins, cutouts, clearance and the Effect footprint on a small, inspectable set.

## Views.svg - nine specimens x three diagnostic views

Each row is one specimen: its CENTERLINE (dashed), its stroke ENVELOPE (filled),
and its FOOTPRINT (envelope + contour, dashed outline).

| Id | What it proves |
| -- | -------------- |
| S1 miter corner | an open angular stroke with a miter join and butt ends |
| S2 bevel corner | the same stroke with a bevel join (the corner is cut, not pointed) |
| S3 butt curve | an open curve with butt terminals |
| S4 round curve | the same curve with round terminals |
| S5 tapered needle | a variable-width profile, pointed at both ends |
| S6 tight hook | a hooked stroke whose inner curve is tight |
| S7 cutout ring | a closed contour with a real even-odd cutout |
| S8 adjacent clearance | two outlined strokes at the minimum footprint clearance |
| S9 echo footprint | the Effect variant, with the echo included in the footprint |

## Clearance (footprints, gap = 1.5)

${Table(Views.report, "specimen")}

## Compositions.svg - four deliberately different scenes

| Id | What it proves |
| -- | -------------- |
| C1 sparse angular | open angular strokes, large negative space |
| C2 dense curved | concentric closed curves, dense detail |
| C3 asymmetric collage | off-centre hook, void ring, small rays |
| C4 balanced radial | eight rays of mixed width, one ring, one core |

## Clearance (compositions, gap = 1.5)

${Table(Compositions.report, "composition")}

## Verdict

${Views.failed.length === 0 && Compositions.failed.length === 0 ? "All specimens and compositions clear their footprints." : `${Views.failed.length + Compositions.failed.length} overlap(s) - see the tables above.`}
`;

writeFileSync(join(Out, "index.md"), Index);

console.log(`specimens: ${Views.report.length} clearance rows, ${Views.failed.length} overlaps`);
console.log(
	`compositions: ${Compositions.report.length} clearance rows, ${Compositions.failed.length} overlaps`,
);
console.log(
	`written: ${join(Out, "Views.svg")}, ${join(Out, "Compositions.svg")}, ${join(Out, "index.md")}`,
);
process.exit(Views.failed.length + Compositions.failed.length === 0 ? 0 : 1);
